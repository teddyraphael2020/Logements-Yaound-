-- IMMO+ — compléments SQL pour historiques, demandes, signalements et administration.
-- À exécuter dans Supabase > SQL Editor, sur le projet ckpcapndbsjmkhshyowg.
-- Les colonnes existantes de logements (id, owner_id, Ville, Quartier, Prix,
-- Type de logement, Description, Statut, photos) sont conservées.

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.type_compte = 'admin'
  );
$$;

create table if not exists public.listing_views (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  logement_id bigint not null references public.logements(id) on delete cascade,
  viewed_at timestamptz not null default now()
);
create index if not exists listing_views_user_viewed_idx on public.listing_views(user_id, viewed_at desc);

create table if not exists public.listing_requests (
  id bigint generated by default as identity primary key,
  logement_id bigint not null references public.logements(id) on delete cascade,
  requester_id uuid not null references auth.users(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  message text not null,
  status text not null default 'nouvelle',
  created_at timestamptz not null default now()
);
create index if not exists listing_requests_owner_created_idx on public.listing_requests(owner_id, created_at desc);
create index if not exists listing_requests_requester_idx on public.listing_requests(requester_id, created_at desc);

create table if not exists public.listing_reports (
  id bigint generated by default as identity primary key,
  logement_id bigint not null references public.logements(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null,
  details text,
  status text not null default 'ouvert',
  created_at timestamptz not null default now()
);
create index if not exists listing_reports_created_idx on public.listing_reports(created_at desc);

alter table public.listing_views enable row level security;
alter table public.profiles enable row level security;
alter table public.listing_requests enable row level security;
alter table public.listing_reports enable row level security;

-- Historique : chaque utilisateur ne voit et n'ajoute que ses propres consultations.
drop policy if exists "ImmoPlus lecture historique personnel" on public.listing_views;
create policy "ImmoPlus lecture historique personnel" on public.listing_views
for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());
drop policy if exists "ImmoPlus ajout historique personnel" on public.listing_views;
create policy "ImmoPlus ajout historique personnel" on public.listing_views
for insert to authenticated with check (user_id = (select auth.uid()) and exists (select 1 from public.logements l where l.id = logement_id));

-- Demandes : le demandeur crée et consulte ses demandes ; le propriétaire les reçoit et les traite.
drop policy if exists "ImmoPlus creation demande" on public.listing_requests;
create policy "ImmoPlus creation demande" on public.listing_requests
for insert to authenticated with check (requester_id = (select auth.uid()) and requester_id <> owner_id and exists (select 1 from public.logements l where l.id = logement_id and l.owner_id = owner_id));
drop policy if exists "ImmoPlus lecture demandes personnelles" on public.listing_requests;
create policy "ImmoPlus lecture demandes personnelles" on public.listing_requests
for select to authenticated using (requester_id = (select auth.uid()) or owner_id = (select auth.uid()) or public.is_admin());
drop policy if exists "ImmoPlus traitement demandes proprietaire" on public.listing_requests;
create policy "ImmoPlus traitement demandes proprietaire" on public.listing_requests
for update to authenticated using (owner_id = (select auth.uid()) or public.is_admin())
with check (owner_id = (select auth.uid()) or public.is_admin());

-- Signalements : création par un utilisateur connecté ; lecture et traitement par l'administration.
drop policy if exists "ImmoPlus creation signalement" on public.listing_reports;
create policy "ImmoPlus creation signalement" on public.listing_reports
for insert to authenticated with check (reporter_id = (select auth.uid()) and exists (select 1 from public.logements l where l.id = logement_id));
drop policy if exists "ImmoPlus lecture signalements admin" on public.listing_reports;
create policy "ImmoPlus lecture signalements admin" on public.listing_reports
for select to authenticated using (public.is_admin());
drop policy if exists "ImmoPlus traitement signalements admin" on public.listing_reports;
create policy "ImmoPlus traitement signalements admin" on public.listing_reports
for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Consultation et modification de son profil. Le profil admin peut consulter/modifier les profils.
drop policy if exists "ImmoPlus lecture profil personnel" on public.profiles;
create policy "ImmoPlus lecture profil personnel" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_admin());
drop policy if exists "ImmoPlus modification profil personnel" on public.profiles;
create policy "ImmoPlus modification profil personnel" on public.profiles
for update to authenticated using (id = (select auth.uid()) or public.is_admin())
with check (id = (select auth.uid()) or public.is_admin());

-- Statistiques générales : les fonctions vérifient le rôle admin côté serveur.
create or replace function public.admin_dashboard_stats()
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare result jsonb;
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  select jsonb_build_object(
    'users', (select count(*) from auth.users),
    'listings', (select count(*) from public.logements),
    'requests', (select count(*) from public.listing_requests),
    'open_reports', (select count(*) from public.listing_reports where status = 'ouvert'),
    'storage_objects', (select count(*) from storage.objects),
    'storage_bytes', (select coalesce(sum(case when (metadata->>'size') ~ '^[0-9]+$' then (metadata->>'size')::bigint else 0 end),0) from storage.objects),
    'admins', (select count(*) from public.profiles where type_compte = 'admin'),
    'pending_requests', (select count(*) from public.listing_requests where status in ('nouvelle','en attente'))
  ) into result;
  return result;
end;
$$;

create or replace function public.admin_list_users()
returns table(id uuid, email text, created_at timestamptz, type_compte text, telephone text, ville text, photo_profil text)
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  return query
  select u.id, u.email::text, u.created_at, p.type_compte, p.telephone, p.ville, p.photo_profil
  from auth.users u left join public.profiles p on p.id = u.id
  order by u.created_at desc limit 200;
end;
$$;

create or replace function public.admin_storage_stats()
returns table(bucket_id text, object_count bigint, total_bytes bigint)
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  return query
  select b.id::text,
         count(o.id)::bigint,
         coalesce(sum(case when (o.metadata->>'size') ~ '^[0-9]+$' then (o.metadata->>'size')::bigint else 0 end),0)::bigint
  from storage.buckets b left join storage.objects o on o.bucket_id = b.id
  group by b.id order by b.id;
end;
$$;

revoke all on function public.admin_dashboard_stats() from public;
revoke all on function public.admin_list_users() from public;
revoke all on function public.admin_storage_stats() from public;
grant execute on function public.admin_dashboard_stats() to authenticated;
grant execute on function public.admin_list_users() to authenticated;
grant execute on function public.admin_storage_stats() to authenticated;
