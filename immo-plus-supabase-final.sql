create policy "ImmoPlus modification personnelle logements-photos" on storage.objects
for update to authenticated using (
  bucket_id = 'logements-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
) with check (
  bucket_id = 'logements-photos' and (storage.foldername(name))[1] = (select auth.uid())::text
);
