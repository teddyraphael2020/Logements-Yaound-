-- Création automatique du profil lors d'une nouvelle inscription, même si la confirmation e-mail est activée.
create or replace function public.handle_new_immoplus_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, type_compte)
  values (new.id, case when new.raw_user_meta_data->>'type_compte' in ('chercheur','proprietaire','agent') then new.raw_user_meta_data->>'type_compte' else 'chercheur' end)
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_immoplus on auth.users;
create trigger on_auth_user_created_immoplus
after insert on auth.users
for each row execute function public.handle_new_immoplus_user();

-- Les fonctions ci-dessous sont les seules voies autorisées pour consulter toutes les demandes
-- et modifier les rôles. Elles vérifient le rôle admin côté serveur.
create or replace function public.admin_set_user_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  if p_role is null or p_role not in ('chercheur','proprietaire','agent','admin') then raise exception 'Rôle non autorisé'; end if;
  insert into public.profiles (id, type_compte)
  values (p_user_id, p_role)
  on conflict (id) do update set type_compte = excluded.type_compte;
end;
$$;

create or replace function public.admin_list_requests()
returns table(request_id bigint, logement_id bigint, requester_id uuid, owner_id uuid,
              requester_email text, owner_email text, message text, status text, created_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Accès administrateur requis'; end if;
  return query
  select r.id, r.logement_id, r.requester_id, r.owner_id,
         ru.email::text, ou.email::text, r.message, r.status, r.created_at
  from public.listing_requests r
  left join auth.users ru on ru.id = r.requester_id
  left join auth.users ou on ou.id = r.owner_id
  order by r.created_at desc limit 500;
end;
$$;

revoke all on function public.admin_set_user_role(uuid,text) from public, anon;
revoke all on function public.admin_list_requests() from public, anon;
grant execute on function public.admin_set_user_role(uuid,text) to authenticated;
grant execute on function public.admin_list_requests() to authenticated;

